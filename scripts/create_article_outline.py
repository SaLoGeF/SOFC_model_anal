"""Generate a Word document with the SOFC article outline."""

from pathlib import Path

from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH

ROOT_DIR = Path(__file__).resolve().parents[1]
OUTPUT_PATH = ROOT_DIR / "article_outline.docx"


def add_heading_text(doc: Document, text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def add_body(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text)
    p.paragraph_format.first_line_indent = Cm(1.25)


def add_quote(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text, style="Intense Quote")


def add_numbered(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Number")


def main() -> None:
    doc = Document()

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    # ---- Название ----
    add_heading_text(doc, "Название", level=1)
    add_body(
        doc,
        "«Суррогатная многокритериальная оптимизация рабочих параметров "
        "твердооксидного топливного элемента на основе ансамблевых моделей "
        "машинного обучения и алгоритма NSGA-II»",
    )
    add_body(
        doc,
        '(англ.: \u201cSurrogate-assisted multi-objective optimization of SOFC '
        'operating parameters using ensemble machine learning and NSGA-II\u201d)',
    )

    # ---- Цель работы ----
    add_heading_text(doc, "Цель работы", level=1)
    add_body(
        doc,
        "Разработка и верификация методики автоматизированного поиска оптимальных "
        "рабочих параметров ТОТЭ (напряжение ячейки, расход воздуха, расход топлива, "
        "температура на входе), обеспечивающих одновременную максимизацию плотности "
        "тока и КПД при минимизации суммарных потерь — без необходимости массового "
        "перебора дорогостоящих CFD-расчётов в ANSYS Fluent.",
    )

    # ---- Абстракт ----
    add_heading_text(doc, "Абстракт", level=1)
    add_body(
        doc,
        "Оптимизация рабочих режимов твердооксидных топливных элементов (ТОТЭ) "
        "традиционно требует многократного запуска детальных физико-химических "
        "CFD-моделей, что сопряжено с высокими вычислительными затратами. "
        "В данной работе предложен подход, при котором на основе ограниченного "
        "набора результатов численного моделирования в ANSYS Fluent (≈150 расчётных "
        "точек) строятся суррогатные модели — ансамбли алгоритмов градиентного "
        "бустинга и случайного леса с полиномиальным расширением признаков. "
        "Построенные суррогаты используются в качестве целевых функций "
        "многокритериального генетического алгоритма NSGA-II для одновременной "
        "оптимизации плотности тока (P76), суммарных потерь (P62) и КПД (P89). "
        "Компромиссное решение выбирается по взвешенному расстоянию до идеальной "
        "точки на фронте Парето. Верификация найденного оптимума путём прямого "
        "расчёта в исходной модели ANSYS Fluent подтверждает высокую точность "
        "суррогатов и эффективность предложенной методики.",
    )

    # ---- Структура статьи ----
    add_heading_text(doc, "Структура статьи", level=1)

    add_heading_text(doc, "1. Введение", level=2)
    add_body(
        doc,
        "Актуальность оптимизации ТОТЭ; проблема вычислительной стоимости полных "
        "CFD-моделей; обзор существующих подходов (DOE, RSM, однокритериальная оптимизация).",
    )

    add_heading_text(doc, "2. Математическая модель ТОТЭ в ANSYS Fluent", level=2)
    add_body(
        doc,
        "Описание CFD-модели ячейки (40×40), используемый модуль SOFC "
        "(Fuel Cell and Electrolysis); входные параметры (P27 — напряжение ячейки, "
        "P46 — расход воздуха, P47 — расход топлива, P52 — температура газа на входе); "
        "выходные характеристики (P76 — плотность тока, P62 — суммарные потери, "
        "P79 — H₂ на выходе, P89 — КПД); план вычислительного эксперимента "
        "(10 серий × 15 расчётных точек).",
    )

    add_heading_text(doc, "3. Построение суррогатных моделей", level=2)
    add_body(
        doc,
        "Агрегация данных из результатов Fluent; feature engineering (обратная величина "
        "1/P27, полиномиальное расширение степени 2); архитектура ансамбля "
        "(VotingRegressor: RF + GBR с log-трансформацией целевой переменной для P76; "
        "RF-пайплайны для P62, P79, P89); оценка качества через 5-fold кросс-валидацию "
        "(R², MAE).",
    )

    add_heading_text(doc, "4. Многокритериальная оптимизация (NSGA-II)", level=2)
    add_body(
        doc,
        "Формализация задачи (max P76, min P62, max P89); операторы (BLX-кроссовер, "
        "гауссова мутация); недоминируемая сортировка и crowding distance; выбор "
        "компромиссного решения по нормализованному расстоянию до идеальной точки "
        "с весами (0.4 / 0.2 / 0.3).",
    )

    add_heading_text(doc, "5. Результаты и верификация", level=2)
    add_body(
        doc,
        "Фронт Парето (суррогатный vs. из исходных данных Fluent); сходимость ГА "
        "по поколениям; сравнение найденного оптимума с прямым CFD-расчётом в "
        "ANSYS Fluent (таблица абсолютных и относительных отклонений); визуализация "
        "точности суррогатов (actual vs. predicted).",
    )

    add_heading_text(doc, "6. Обсуждение", level=2)
    add_body(
        doc,
        "Анализ чувствительности к весам целевых функций; влияние размера обучающей "
        "выборки на точность суррогатов; границы применимости подхода; сравнение "
        "с ручным подбором.",
    )

    add_heading_text(doc, "7. Заключение", level=2)
    add_body(
        doc,
        "Основные выводы; рекомендации для практического применения; направления "
        "дальнейших исследований.",
    )

    # ---- Научная новизна ----
    add_heading_text(doc, "Научная новизна", level=1)

    add_heading_text(doc, "1. Суррогатная замена дорогостоящей CFD-модели", level=2)
    add_body(
        doc,
        "Большинство работ по оптимизации ТОТЭ либо используют упрощённые "
        "аналитические модели, либо требуют тысяч запусков полной 3D-модели. "
        "Здесь показано, что ≈150 расчётных точек Fluent достаточно для "
        "построения адекватных суррогатов и нахождения оптимума, что снижает "
        "вычислительные затраты на 2–3 порядка по сравнению с прямой оптимизацией "
        "на CFD-модели.",
    )

    add_heading_text(doc, "2. Физически мотивированный feature engineering для ансамблей", level=2)
    add_body(
        doc,
        "Введение обратной величины 1/P27 для захвата нелинейного (экспоненциального) "
        "роста плотности тока при снижении напряжения ячейки — приём, основанный "
        "на электрохимии ТОТЭ (уравнение Батлера–Вольмера), не встречающийся "
        "в типичных surrogate-assisted optimization пайплайнах для топливных элементов.",
    )

    add_heading_text(doc, "3. Замкнутый цикл «CFD → суррогат → оптимизация → верификация в CFD»", level=2)
    add_body(
        doc,
        "В отличие от работ, ограничивающихся суррогатной оптимизацией без проверки, "
        "здесь найденные ГА параметры подставляются обратно в полную модель ANSYS Fluent "
        "и погрешность количественно оценена — что доказывает практическую пригодность "
        "методики.",
    )

    add_heading_text(doc, "4. Воспроизводимый открытый pipeline", level=2)
    add_body(
        doc,
        "Весь цикл (парсинг результатов Fluent → агрегация → ML-суррогаты → NSGA-II → "
        "верификация) реализован как программный pipeline на Python, что обеспечивает "
        "воспроизводимость и отличает работу от «чёрных ящиков» коммерческих "
        "оптимизаторов (ANSYS DesignXplorer, modeFRONTIER и т.д.).",
    )

    doc.save(str(OUTPUT_PATH))
    print(f"Saved: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
